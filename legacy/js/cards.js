/* ══════════════════════════════════════════════════════════════
   cards.js — Character cards (SillyTavern spec v1 / v2 / v3)

   A card is a PNG with its character data hidden in a tEXt chunk —
   keyword `chara` for spec v2, `ccv3` for spec v3 — holding
   base64-encoded JSON. That is the entire format. When a card
   carries both, v3 wins.

   Cards reach the registry two ways:

     • cards/cards.js — a manifest generated by tools/sync-cards.js
       straight out of a real SillyTavern install. It is a plain
       <script> assignment rather than JSON on purpose: fetch() is
       blocked on a bare file:// page, and this app must still open
       as one.

     • the in-app editor and file picker, which keep card text in
       localStorage and avatars in IndexedDB (a card PNG is ~1MB,
       far past localStorage's budget).

   The registry merges both, keyed by a stable hash of the card's
   name and description, so re-syncing never duplicates an entry and
   an ST re-export (which rewrites creator_notes constantly) does not
   either.
   ══════════════════════════════════════════════════════════════ */

const CARDS_KEY = "chatchat_cards";
const CARDS_HIDDEN_KEY = "chatchat_cards_hidden";
const CARD_AVATAR_DB = "chatchat-cards";
const CARD_AVATAR_STORE = "avatars";

/** Byte order mark of every PNG. */
const PNG_SIG = [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a];

/* ── Identity ──────────────────────────────────────────────────── */

/**
 * Stable id for a card.
 *
 * Hashes name + description only. `creator_notes`, `character_version`
 * and `extensions` change on every ST re-export and would otherwise
 * mint a duplicate card each time the folder is re-synced.
 * @param {{name:string, description:string}} card
 * @returns {string}
 */
function cardId(card) {
  const src = (card.name || "") + "\u0000" + (card.description || "");
  let h = 5381;
  for (let i = 0; i < src.length; i++) h = ((h << 5) + h + src.charCodeAt(i)) | 0;
  return "card_" + (h >>> 0).toString(36);
}

/* ── PNG chunk reading ─────────────────────────────────────────── */

/** Decode bytes as latin1 (PNG keywords and text payloads are latin1). */
function latin1(bytes) {
  let out = "";
  for (let i = 0; i < bytes.length; i++) out += String.fromCharCode(bytes[i]);
  return out;
}

/** Read a NUL-terminated latin1 string; returns { text, next } past the NUL. */
function readCString(bytes, start) {
  let end = start;
  while (end < bytes.length && bytes[end] !== 0) end++;
  return { text: latin1(bytes.subarray(start, end)), next: end + 1 };
}

/** Inflate zlib-wrapped deflate, as used by zTXt and compressed iTXt. */
async function inflateChunk(bytes) {
  if (typeof DecompressionStream !== "function") {
    throw new Error("This card is zTXt-compressed and the browser cannot inflate it.");
  }
  const stream = new Blob([bytes])
    .stream()
    .pipeThrough(new DecompressionStream("deflate"));
  return new Uint8Array(await new Response(stream).arrayBuffer());
}

/**
 * Decode one PNG text chunk into { keyword, value }.
 * Handles tEXt (plain), zTXt (deflate) and iTXt (international, either).
 * @returns {Promise<{keyword:string, value:string}|null>}
 */
async function decodeTextChunk(type, chunk) {
  if (type === "tEXt") {
    const key = readCString(chunk, 0);
    return { keyword: key.text, value: latin1(chunk.subarray(key.next)) };
  }

  if (type === "zTXt") {
    const key = readCString(chunk, 0);
    const body = await inflateChunk(chunk.subarray(key.next + 1)); // +1 skips the compression method byte
    return { keyword: key.text, value: latin1(body) };
  }

  if (type === "iTXt") {
    const key = readCString(chunk, 0);
    const compressed = chunk[key.next] === 1;
    // compression flag, compression method, language tag, translated keyword
    const lang = readCString(chunk, key.next + 2);
    const translated = readCString(chunk, lang.next);
    const body = chunk.subarray(translated.next);
    const bytes = compressed ? await inflateChunk(body) : body;
    return { keyword: key.text, value: new TextDecoder("utf-8").decode(bytes) };
  }

  return null;
}

/**
 * Extract the character JSON payload from a PNG buffer.
 * @param {ArrayBuffer} buffer
 * @returns {Promise<object>} Parsed card JSON (still in its raw v1/v2/v3 shape)
 */
async function readCardJsonFromPng(buffer) {
  const bytes = new Uint8Array(buffer);
  if (bytes.length < 8 || PNG_SIG.some((b, i) => bytes[i] !== b)) {
    throw new Error("Not a PNG file");
  }

  const view = new DataView(buffer);
  const found = {};
  let off = 8;

  while (off + 8 <= bytes.length) {
    const len = view.getUint32(off);
    const type = String.fromCharCode(
      bytes[off + 4],
      bytes[off + 5],
      bytes[off + 6],
      bytes[off + 7],
    );
    const dataStart = off + 8;
    const dataEnd = dataStart + len;
    if (type === "IEND" || dataEnd > bytes.length) break;

    if (type === "tEXt" || type === "zTXt" || type === "iTXt") {
      try {
        const text = await decodeTextChunk(type, bytes.subarray(dataStart, dataEnd));
        if (text && (text.keyword === "chara" || text.keyword === "ccv3")) {
          found[text.keyword] = text.value;
        }
      } catch (e) {
        // A chunk we cannot read is not fatal — the other one may still work.
        console.warn("Skipping unreadable " + type + " chunk:", e);
      }
    }
    off = dataEnd + 4; // + CRC32
  }

  const payload = found.ccv3 || found.chara;
  if (!payload) {
    throw new Error("PNG has no character data (no chara/ccv3 chunk)");
  }

  // base64 → UTF-8. NOT atob() straight to a string: card names and
  // descriptions are routinely non-ASCII and would come out as mojibake.
  const bin = atob(payload.replace(/\s/g, ""));
  const raw = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) raw[i] = bin.charCodeAt(i);
  return JSON.parse(new TextDecoder("utf-8").decode(raw));
}

/* ── Normalisation ─────────────────────────────────────────────── */

function asString(v) {
  return typeof v === "string" ? v : "";
}

function asStringArray(v) {
  if (typeof v === "string") return v ? [v] : [];
  return Array.isArray(v) ? v.filter((s) => typeof s === "string" && s) : [];
}

/**
 * Flatten a character_book (lorebook) into the handful of fields the
 * keyword scanner actually uses. Entries arrive either as an array (v3)
 * or as an id-keyed object (some v2 exports).
 * @returns {Array<object>|null}
 */
function normalizeCharacterBook(book) {
  if (!book) return null;
  let entries = book.entries;
  if (entries && !Array.isArray(entries)) entries = Object.values(entries);
  if (!Array.isArray(entries) || entries.length === 0) return null;

  return entries
    .filter((e) => e && typeof e === "object" && asString(e.content))
    .map((e) => ({
      keys: asStringArray(e.keys || e.key),
      secondaryKeys: asStringArray(e.secondary_keys || e.keysecondary),
      content: asString(e.content),
      // Constant entries are always injected; the rest are keyword-triggered.
      constant: !!e.constant,
      enabled: e.enabled !== false,
      caseSensitive: !!e.case_sensitive,
      insertionOrder: typeof e.insertion_order === "number" ? e.insertion_order : 100,
    }))
    .filter((e) => e.enabled);
}

/**
 * Normalise any card generation into chatchat's canonical shape.
 *
 * Handles three shapes: spec v2/v3 (`{spec, data:{…}}`), v1 (flat), and
 * the loose `{name, description, …}` objects people paste by hand.
 * @param {object} raw
 * @returns {object|null} null when there is no usable name
 */
function normalizeCard(raw) {
  if (!raw || typeof raw !== "object") return null;
  const d = raw.data && typeof raw.data === "object" ? raw.data : raw;
  const name = asString(d.name).trim();
  if (!name) return null;

  const card = {
    name: name,
    description: asString(d.description),
    personality: asString(d.personality),
    scenario: asString(d.scenario),
    firstMes: asString(d.first_mes),
    mesExample: asString(d.mes_example),
    systemPrompt: asString(d.system_prompt),
    postHistoryInstructions: asString(d.post_history_instructions),
    alternateGreetings: asStringArray(d.alternate_greetings),
    groupOnlyGreetings: asStringArray(d.group_only_greetings),
    tags: asStringArray(d.tags),
    creator: asString(d.creator),
    characterVersion: asString(d.character_version),
    creatorNotes: asString(d.creator_notes),
    characterBook: normalizeCharacterBook(d.character_book),
    spec: raw.spec || (d === raw ? "chara_card_v1" : "chara_card_v2"),
  };

  // A hand-written character only ever fills a couple of fields; give
  // the image layer something to work with rather than nothing.
  card.appearance = asString(d.appearance) || extractAppearance(card);
  card.id = cardId(card);
  return card;
}

/**
 * Words that indicate a physical descriptor.
 */
const APPEARANCE_CUES =
  /\b(hair|eyes?|skin|complexion|tall|short|height|build|slender|lean|muscular|curvy|petite|statuesque|frame|face|freckles?|scar|tattoo|piercing|ears?|tail|horns?|wings?|fur|scales|fangs?|claws?|beard|stubble|braid|ponytail|bun|curls?|blonde|brunette|raven|silver|white-haired|ginger|auburn|amber|emerald|azure|violet|crimson|pale|porcelain|tan|olive|dark-skinned|elf|orc|demon|angel|vampire|werewolf|kitsune|neko|dragon|centaur|tiefling|humanoid|mid-?twenties|mid-?thirties|teen|young woman|young man)\b/i;

/**
 * Phrases that mark a clause as prompt engineering rather than a person.
 * Cards aimed at image generators routinely carry paragraphs of "always
 * include…" / "LOCK: every later image…" instructions, and those must not
 * end up substituted into every prompt as if they described a body.
 */
const APPEARANCE_NOISE =
  /\{\{|\}\}|\b(lock|locked|token|prompt|instructions?|negative|render|subject features|every later|every subsequent|step \d|aspect ratio|style|do not|don't|never|always|must|should)\b/i;

/**
 * Sentence-level physical descriptors, used to seed a locked image
 * appearance when a card joins a chat's cast.
 *
 * Deliberately conservative. A card is written for a language model, so
 * prose about feelings sits right next to prose about hair colour — a
 * whole-sentence match drags in "quietly mortified that she's started
 * liking her post-baby body", which is exactly the kind of thing that
 * should never be substituted into an image prompt. So: prefer an
 * explicit "Appearance:" section, then score individual comma-separated
 * clauses rather than sentences, and drop anything that smells like
 * prompt engineering. The result is a seed, editable in the card editor.
 *
 * @param {{description:string}} card
 * @returns {string} comma-joined appearance phrases ("" when nothing matched)
 */
function extractAppearance(card) {
  let text = String(card.description || "");

  // Example dialogue and actions are never descriptive prose.
  text = text.split(/\{\{char\}\}\s*:/i)[0].split(/\{\{user\}\}\s*:/i)[0];
  text = text.replace(/\*[^*]*\*/g, " ");

  // Cards often wrap traits in a structured block: [Name's body= "a", "b"]
  text = text.replace(/\[([^\]]*)\]/g, "$1");

  // An explicit heading is authoritative; stop at the next "Word:" heading.
  const headed = text.match(/appearance\s*[:\-]\s*([\s\S]{0,500})/i);
  const source = headed
    ? headed[1].split(/\n\s*\**[A-Z][A-Za-z' ]{2,24}\**[\s\S]{0,2}[:\-]/)[0]
    : text;

  const clauses = source
    .split(/[,;\n]|\.\s+/)
    // Strip bullets and emphasis, but not digits or quotes — "5'2\" tall"
    // must survive intact.
    .map((s) =>
      s
        // A structured block loses its brackets above, leaving a
        // "Seraphina's body= \"pink hair\"" prefix on the first clause.
        .replace(/^[\s*\-–—•]+/, "")
        .replace(/^\S+'?s?\s+(?:body|appearance|look|physique)\s*[=:]\s*/i, "")
        .replace(/^["“”'‘’]+/, "")
        .replace(/["“”'‘’]+$/, "")
        .trim(),
    )
    .filter(Boolean);

  const hits = clauses.filter(
    (c) => c.length >= 2 && c.length <= 90 && APPEARANCE_CUES.test(c) && !APPEARANCE_NOISE.test(c),
  );

  // Drop whole clauses rather than slicing mid-word: this string is injected
  // into every image prompt for the character, so a dangling "…with strands
  // esca" is worse than one fewer trait. The final slice is a backstop for a
  // single clause that is already over the cap on its own.
  const kept = [...new Set(hits)];
  let out = kept.join(", ");
  while (out.length > 300 && kept.length > 1) {
    kept.pop();
    out = kept.join(", ");
  }
  return out.slice(0, 300).trim();
}

/**
 * Split a card's `mes_example` into individual example turns.
 * ST separates them with a literal `<START>` marker.
 * @param {string} str
 * @returns {string[]}
 */
function parseMesExample(str) {
  if (!str) return [];
  return str
    .split(/<START>/i)
    .map((s) => s.trim())
    .filter(Boolean);
}

/** Every opening scene a card offers: first_mes followed by alternates. */
function cardGreetings(card) {
  if (!card) return [];
  return [card.firstMes]
    .concat(card.alternateGreetings || [])
    .filter((g) => g && g.trim());
}

/* ── Registry ──────────────────────────────────────────────────── */

function getStoredCards() {
  const list = safeGetJSON(CARDS_KEY, []);
  return Array.isArray(list) ? list : [];
}

function setStoredCards(list) {
  safeSetItem(CARDS_KEY, JSON.stringify(list));
}

/** Card ids the user deleted, so a re-sync does not resurrect them. */
function getHiddenCardIds() {
  const list = safeGetJSON(CARDS_HIDDEN_KEY, []);
  return Array.isArray(list) ? list : [];
}

/** Cards emitted by tools/sync-cards.js. Absent when never run. */
function getSyncedCards() {
  return Array.isArray(window.CHATCHAT_CARDS) ? window.CHATCHAT_CARDS : [];
}

/**
 * Every known card. Synced cards load first so a user edit of the same
 * card wins, and hidden ids are filtered out last.
 * @returns {Array<object>}
 */
function getCards() {
  const hidden = new Set(getHiddenCardIds());
  const byId = new Map();
  getSyncedCards().forEach((c) => {
    if (c && c.id) byId.set(c.id, Object.assign({ source: "sync" }, c));
  });
  getStoredCards().forEach((c) => {
    if (c && c.id) byId.set(c.id, Object.assign({ source: "user" }, c));
  });
  return [...byId.values()].filter((c) => !hidden.has(c.id));
}

/** @returns {object|null} */
function getCard(id) {
  return getCards().find((c) => c.id === id) || null;
}

/** Cards for the given ids, in that order, skipping anything deleted. */
function getCardsByIds(ids) {
  return (ids || []).map(getCard).filter(Boolean);
}

/**
 * Cards currently cast in this chat, lead first.
 * @returns {Array<object>}
 */
function getCast() {
  return getCardsByIds(storyConfig.castIds);
}

/** Add or replace a user-owned card. */
function saveCard(card) {
  card.id = card.id || cardId(card);
  const list = getStoredCards();
  const at = list.findIndex((c) => c.id === card.id);
  if (at >= 0) list[at] = card;
  else list.push(card);
  setStoredCards(list);
  // Editing a synced card into existence means it is no longer hidden.
  setHiddenCardIds(getHiddenCardIds().filter((id) => id !== card.id));
}

function setHiddenCardIds(ids) {
  safeSetItem(CARDS_HIDDEN_KEY, JSON.stringify(ids));
}

/**
 * Remove a card from the library. Synced cards are tombstoned rather
 * than deleted, so the next sync does not bring them straight back.
 */
function deleteCard(id) {
  setStoredCards(getStoredCards().filter((c) => c.id !== id));
  if (getSyncedCards().some((c) => c.id === id)) {
    const hidden = getHiddenCardIds();
    if (!hidden.includes(id)) hidden.push(id);
    setHiddenCardIds(hidden);
  }
  removeCardFromCast(id);
}

/** Drop a card from the active chat's cast (e.g. after it is deleted). */
function removeCardFromCast(id) {
  if (!storyConfig.castIds) return;
  const before = storyConfig.castIds.length;
  storyConfig.castIds = storyConfig.castIds.filter((c) => c !== id);
  if (storyConfig.castIds.length !== before && typeof saveStoryConfig === "function") {
    saveStoryConfig();
  }
}

/* ── Avatar blobs (IndexedDB) ──────────────────────────────────── */

let _cardDbPromise = null;

function openCardDb() {
  if (_cardDbPromise) return _cardDbPromise;
  _cardDbPromise = new Promise((resolve, reject) => {
    const req = indexedDB.open(CARD_AVATAR_DB, 1);
    req.onupgradeneeded = () => {
      const db = req.result;
      if (!db.objectStoreNames.contains(CARD_AVATAR_STORE)) {
        db.createObjectStore(CARD_AVATAR_STORE, { keyPath: "id" });
      }
    };
    req.onsuccess = () => resolve(req.result);
    req.onerror = () => reject(req.error);
  });
  // Don't cache a rejected open — a later call should retry.
  _cardDbPromise.catch(() => {
    _cardDbPromise = null;
  });
  return _cardDbPromise;
}

/** @param {string} id @param {string} dataUrl @returns {Promise<void>} */
async function putCardAvatar(id, dataUrl) {
  const db = await openCardDb();
  const tx = db.transaction(CARD_AVATAR_STORE, "readwrite");
  tx.objectStore(CARD_AVATAR_STORE).put({ id: id, dataUrl: dataUrl });
  await new Promise((resolve, reject) => {
    tx.oncomplete = resolve;
    tx.onerror = () => reject(tx.error);
  });
}

/** @param {string} id @returns {Promise<string|null>} data URL, or null */
async function getCardAvatar(id) {
  try {
    const db = await openCardDb();
    const tx = db.transaction(CARD_AVATAR_STORE, "readonly");
    const rec = await new Promise((resolve, reject) => {
      const req = tx.objectStore(CARD_AVATAR_STORE).get(id);
      req.onsuccess = () => resolve(req.result);
      req.onerror = () => reject(req.error);
    });
    return rec ? rec.dataUrl : null;
  } catch (e) {
    return null;
  }
}

/** @param {string} id */
async function deleteCardAvatar(id) {
  try {
    const db = await openCardDb();
    const tx = db.transaction(CARD_AVATAR_STORE, "readwrite");
    tx.objectStore(CARD_AVATAR_STORE).delete(id);
  } catch (e) {
    /* nothing to clean up */
  }
}

/** Blob → data URL, for storing an avatar or previewing a dropped PNG. */
function fileToDataUrl(file) {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => resolve(reader.result);
    reader.onerror = () => reject(reader.error);
    reader.readAsDataURL(file);
  });
}

/* ── Import ────────────────────────────────────────────────────── */

/**
 * Import dropped or picked files as cards.
 *
 * `.png` is read from its embedded chunks; `.json` accepts a bare card,
 * a v2/v3 wrapper, or an array of either. Avatars are kept in IndexedDB
 * keyed by card id. `.charx` archives are not supported yet.
 *
 * @param {FileList|File[]} files
 * @returns {Promise<{added:number, updated:number, skipped:string[]}>}
 */
async function importCardFiles(files) {
  const result = { added: 0, updated: 0, skipped: [] };
  const known = new Set(getCards().map((c) => c.id));

  for (const file of Array.from(files)) {
    const lower = (file.name || "").toLowerCase();
    try {
      if (lower.endsWith(".png")) {
        const card = normalizeCard(await readCardJsonFromPng(await file.arrayBuffer()));
        if (!card) throw new Error("no usable character name");
        const existed = known.has(card.id);
        saveCard(card);
        await putCardAvatar(card.id, await fileToDataUrl(file));
        known.add(card.id);
        existed ? result.updated++ : result.added++;
      } else if (lower.endsWith(".json")) {
        const parsed = JSON.parse(await file.text());
        const raws = Array.isArray(parsed) ? parsed : [parsed];
        for (const raw of raws) {
          const card = normalizeCard(raw);
          if (!card) throw new Error("no usable character name");
          const existed = known.has(card.id);
          saveCard(card);
          known.add(card.id);
          existed ? result.updated++ : result.added++;
        }
      } else {
        result.skipped.push(file.name);
      }
    } catch (e) {
      console.warn("Card import failed for " + file.name + ":", e);
      result.skipped.push(file.name);
    }
  }

  return result;
}

/** Read a single dropped/picked PNG into a card without saving it (preview). */
async function readCardFile(file) {
  if ((file.name || "").toLowerCase().endsWith(".png")) {
    return normalizeCard(await readCardJsonFromPng(await file.arrayBuffer()));
  }
  return normalizeCard(JSON.parse(await file.text()));
}
